"""Command-line entry point: `python -m app.cli --help`."""
import argparse
from app.core import milestone_1, milestone_2, milestone_4, milestone_5, milestone_6


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(
        prog="stylistic-text-generator-comparator",
        description="Compare stylistic sports commentary generated by a LoRA-adapted LLM vs an N-gram model.",
    )
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("hello", help="check that everything is wired up")
    sub.add_parser("prepare", help="Milestone 1: clean and tokenize sports commentary corpus")

    p_ngram = sub.add_parser("ngram", help="Milestone 2: generate commentary using the N-gram model")
    p_ngram.add_argument("--prompt", default="Short of a length")
    p_ngram.add_argument("--tokens", type=int, default=24)
    p_ngram.add_argument("--temp", type=float, default=0.8)

    p_train = sub.add_parser("train", help="Milestone 4: fine-tune the LoRA adapter")
    p_train.add_argument("--epochs", type=int, default=3)

    p_gen = sub.add_parser("generate", help="Milestone 5: generate commentary using LoRA-adapted distilgpt2")
    p_gen.add_argument("--prompt", default="Short of a length")
    p_gen.add_argument("--tokens", type=int, default=28)
    p_gen.add_argument("--temp", type=float, default=0.8)

    p_cmp = sub.add_parser("compare", help="Milestone 6: side-by-side comparison across N-gram, Base LLM, and LoRA LLM")
    p_cmp.add_argument("--prompt", default="Full toss on middle stump,")
    p_cmp.add_argument("--tokens", type=int, default=28)
    p_cmp.add_argument("--temp", type=float, default=0.8)

    args = parser.parse_args(argv)
    if args.command == "hello":
        print("Stylistic Text Generator Comparator is ready. Open README.md for your milestones.")
    elif args.command == "prepare":
        print(milestone_1())
    elif args.command == "ngram":
        print(milestone_2(prompt=args.prompt, max_words=args.tokens, temperature=args.temp))
    elif args.command == "train":
        print(milestone_4(epochs=args.epochs))
    elif args.command == "generate":
        print(milestone_5(prompt=args.prompt, max_new_tokens=args.tokens, temperature=args.temp))
    elif args.command == "compare":
        milestone_6(prompt=args.prompt, max_tokens=args.tokens, temperature=args.temp, render=True)


if __name__ == "__main__":
    main()
